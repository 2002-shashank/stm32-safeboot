#!/usr/bin/env python3
"""Regenerate metrics/metrics.md from the raw results in metrics/ and the
linker map files in build/target. Run after any build or measurement."""
from __future__ import annotations

import csv
import json
import re
import subprocess
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
M = ROOT / "metrics"
BUILD = ROOT / "build" / "target" / "target"
SIZE = Path.home() / "opt/arm-gnu-toolchain-15.3.rel2/bin/arm-none-eabi-size"


def load(name: str):
    p = M / name
    if not p.exists():
        return None
    return json.loads(p.read_text()) if p.suffix == ".json" else list(csv.DictReader(p.open()))


def module_sizes(map_path: Path) -> dict[str, int]:
    """Bytes of flash (.text/.rodata/.data load image) per object file."""
    sizes: dict[str, int] = defaultdict(int)
    text = map_path.read_text().split("Linker script and memory map", 1)[-1]
    pend = None
    for line in text.splitlines():
        m = re.match(r"^ (\.(?:text|rodata|data|ramfunc|isr_vector|sb_api)\S*)\s*$", line)
        if m:
            pend = m.group(1)
            continue
        m = re.match(r"^ (\.(?:text|rodata|data|ramfunc|isr_vector|sb_api)\S*)?\s+0x([0-9a-f]+)\s+0x([0-9a-f]+)\s+(\S+\.(?:o|obj|a\(.*\)))$", line)
        if m and (m.group(1) or pend):
            size = int(m.group(3), 16)
            obj = Path(m.group(4).split("(")[-1].rstrip(")")).name
            obj = re.sub(r"\.(c\.)?obj$|\.o$", "", obj)
            sizes[obj] += size
        pend = None
    return dict(sorted(sizes.items(), key=lambda kv: -kv[1]))


def elf_size(name: str) -> tuple[int, int, int] | None:
    elf = BUILD / f"{name}.elf"
    if not elf.exists():
        return None
    out = subprocess.run([str(SIZE), str(elf)], capture_output=True, text=True).stdout.splitlines()
    t, d, b = (int(x) for x in out[1].split()[:3])
    return t, d, b


def main() -> None:
    o: list[str] = ["# Metrics", "",
                    "Generated by `tools/metrics_report.py` from the raw files in this directory. "
                    "Board: STM32F407G-DISC1 MB997E, 168 MHz from HSE, VDD 2.90 V. "
                    "Toolchain: Arm GNU 15.3.Rel2, `-Os`.", ""]

    o += ["## Sizes", "", "| Image | text | data | bss | flash use |", "|---|---|---|---|---|"]
    for name, budget in [("bootloader", 32512), ("bootloader_fi", 32512), ("app_a_v1", 392704),
                         ("app_a_max", 392704), ("bench", None), ("feasibility_blink", None)]:
        s = elf_size(name)
        if s:
            use = f"{(s[0] + s[1]) / budget * 100:.1f}% of {budget} B" if budget else "—"
            o.append(f"| {name} | {s[0]} | {s[1]} | {s[2]} | {use} |")
    mp = BUILD.parent / "bootloader.map"   # ld writes maps in its working dir
    if mp.exists():
        o += ["", "Bootloader flash by module (from the linker map):", "",
              "| Module | Bytes |", "|---|---|"]
        o += [f"| {k} | {v} |" for k, v in list(module_sizes(mp).items())[:14]]
    o.append("")

    b = load("board_bench.json")
    if b:
        o += ["## Crypto, flash and journal (on board, `board_bench.json`)", "",
              "| Measurement | Value |", "|---|---|",
              f"| SHA-256 throughput | {b['sha256_MBps']:.2f} MB/s ({b['sha256_cycles_per_byte']:.1f} cycles/B) |",
              f"| SHA-256, 64 KB / 384 KB | {b['sha256_64k_us'] / 1000:.1f} ms / {b['sha256_384k_us'] / 1000:.1f} ms |",
              f"| Ed25519 verify (Monocypher 4.0.2) | {b['ed25519_verify_us'] / 1000:.2f} ms ({b['ed25519_verify_cycles']} cycles), stack {b['ed25519_stack_bytes']} B |",
              f"| Ed25519 accepts reference signature / rejects tampered | {bool(b['ed25519_ok'])} / {bool(b['ed25519_tampered_rejected'])} |",
              f"| CRC32 (nibble table), 1 KB | {b['crc32_1k_us']:.0f} µs |",
              f"| Sector erase 16 / 64 / 128 KB | {b['erase_16k_ms']:.0f} / {b['erase_64k_ms']:.0f} / {b['erase_128k_ms']:.0f} ms |",
              f"| Word program | {b['program_us_per_word']:.1f} µs/word, {b['program_KBps']:.0f} KB/s |",
              f"| Journal scan empty / full page | {b['journal_scan_empty_us'] / 1000:.2f} / {b['journal_scan_full_page_us'] / 1000:.2f} ms |",
              f"| Journal append / compacting append | {b['journal_append_us']:.0f} µs / {b['journal_compacting_append_ms']:.0f} ms |",
              ""]

    bt = load("board_boot_timing.json")
    if bt:
        o += ["## Validated boot time (DWT, on board, `board_boot_timing.json`)", "",
              "| Segment | " + " | ".join(bt) + " |", "|---|" + "---|" * len(bt)]
        segs = list(next(iter(bt.values()))["segments_us"])
        for s in segs:
            o.append(f"| {s} | " + " | ".join(str(v["segments_us"][s]) for v in bt.values()) + " |")
        o += ["", "Reset release → first instruction is not visible to DWT and is not included "
              "(it needs a GPIO and a logic analyzer).", ""]

    sc = load("board_scenarios.json")
    if sc:
        mm = sc.get("metrics", {})
        o += ["## Rollback and recovery (on board)", "", "| Measurement | Value |", "|---|---|"]
        if "rollback_crash_ms" in mm:
            o.append(f"| Rollback after 3 crashing trial boots (first trial → previous image boots) | {mm['rollback_crash_ms']:.0f} ms |")
        if "rollback_hang_ms" in mm:
            o.append(f"| Rollback after 3 hanging trial boots (IWDG 4 s nominal) | {mm['rollback_hang_ms'] / 1000:.2f} s |")
        o += ["| Empty device → bootloader recovery mode | 2.7 ms (DWT, logged by the bootloader) |",
              "", "Rollback times are host-observed via RTT (±1 ms polling plus USB latency).", ""]
        checks = [c for v in sc.get("scenarios", {}).values() for c in v]
        if checks:
            o += [f"Functional on-board checks: **{sum(ok for _, ok in checks)}/{len(checks)} passed**.", ""]

    fs = load("fault_sim.csv")
    if fs:
        o += ["## Fault tests: simulator (`fault_sim.csv`)", "",
              "Power cut at each flash op × 5 variants (not done / done / torn / torn-prefix / sparse partial erase).", "",
              "| Scenario | Mode | Flash ops | Cut points | Runs | Passed |", "|---|---|---|---|---|---|"]
        tot = [0, 0]
        for r in fs:
            o.append(f"| {r['scenario']} | {r['mode']} | {r['flash_ops']} | {r['cut_points']} | {r['runs']} | {r['passed']} |")
            tot[0] += int(r["runs"])
            tot[1] += int(r["passed"])
        o += [f"| **total** | | | | **{tot[0]}** | **{tot[1]}** |", ""]

    fi = load("board_fault_injection.json")
    if fi:
        o += ["## Fault tests: silicon (`board_fault_injection.json`)", "",
              "Chip reset before / after / in the middle of each flash op (mid-op aborts a real word "
              "program 3, 8 or 13 µs in, or a real sector erase 1, 50, 100 or 180 ms in).", "",
              "| Scenario | Flash ops | Modes | Runs | Passed |", "|---|---|---|---|---|"]
        for r in fi:
            if r:
                o.append(f"| {r['scenario']} | {r['flash_ops']} | {r['modes']} | {r['runs']} | {r['passed']} |")
        o.append("")
    o += ["## Fault tests: real power cuts", "", "**Not tested**: no power-switching rig "
          "(MOSFET or USB relay). Software and mid-op resets above are the substitute; "
          "brown-out behavior is not covered.", ""]

    ret = load("board_retention.json")
    if ret:
        o += ["## Reset retention (`board_retention.json`)", "",
              "| Reset | RCC_CSR flags | Backup SRAM kept | .noinit kept |", "|---|---|---|---|"]
        for r in ret:
            o.append(f"| {r['reset']} | {', '.join(r['rcc_csr_flags'])} | {r['bkpsram_kept']} | {r['noinit_ram_kept']} |")
        pc = load("board_retention_powercycle.json")
        if pc:
            for r in pc:
                o.append(f"| {r['reset']} | {', '.join(r['rcc_csr_flags'])} | {r['bkpsram_kept']} | {r['noinit_ram_kept']} |")
        else:
            o.append("| Power cycle | not yet measured (needs a manual USB unplug) | | |")
        o.append("")

    o += ["## Not yet measured", "",
          "- UART throughput, resume and retry behavior (waiting for the CP2102 adapter).",
          "- The erase-stall test: UART DMA RX during a 128 KB erase (needs UART).",
          "- Reset release → first instruction (needs a logic analyzer).", ""]
    (M / "metrics.md").write_text("\n".join(o))
    print(f"wrote {M / 'metrics.md'}")


if __name__ == "__main__":
    main()
